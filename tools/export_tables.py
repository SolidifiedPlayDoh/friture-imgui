"""Export Friture's precomputed DSP tables to C++ headers.

Run from a checkout of upstream Friture (which provides the `friture` package):

    cd <friture checkout>
    uv run python <this repo>/tools/export_tables.py <this repo>/src/dsp

Outputs generated_filters.hpp and generated_cmap.hpp.
"""
import sys
from pathlib import Path

import numpy as np

from friture import generated_filters
from friture.plotting import generated_cmrmap


def fmt(values):
    return ", ".join(repr(float(v)) for v in np.asarray(values).ravel())


def export_filters(out: Path):
    P = generated_filters.PARAMS
    lines = [
        "// Generated by tools/export_tables.py from Friture's generated_filters.PARAMS.",
        "// Do not edit by hand.",
        "#pragma once",
        "",
        "namespace fr::tables {",
        "",
    ]

    bdec, adec = P["dec"]
    lines.append(f"constexpr int kDecLen = {len(bdec)};")
    lines.append(f"constexpr double kDecB[kDecLen] = {{{fmt(bdec)}}};")
    lines.append(f"constexpr double kDecA[kDecLen] = {{{fmt(adec)}}};")
    lines.append("")

    for key in ("1", "3", "6", "12", "24"):
        b, a, fi, flow, fhigh = P[key]
        b = np.asarray(b)
        a = np.asarray(a)
        n, order = b.shape
        assert a.shape == b.shape
        lines.append(f"// {key} band(s) per octave")
        lines.append(f"constexpr int kBands_{key} = {n};")
        lines.append(f"constexpr int kOrder_{key} = {order};")
        lines.append(f"constexpr double kB_{key}[kBands_{key} * kOrder_{key}] = {{{fmt(b)}}};")
        lines.append(f"constexpr double kA_{key}[kBands_{key} * kOrder_{key}] = {{{fmt(a)}}};")
        lines.append(f"constexpr double kFi_{key}[kBands_{key}] = {{{fmt(fi)}}};")
        lines.append(f"constexpr double kFlow_{key}[kBands_{key}] = {{{fmt(flow)}}};")
        lines.append(f"constexpr double kFhigh_{key}[kBands_{key}] = {{{fmt(fhigh)}}};")
        lines.append("")

    lines.append("}  // namespace fr::tables")
    (out / "generated_filters.hpp").write_text("\n".join(lines) + "\n")


def export_cmap(out: Path):
    cmap = np.asarray(generated_cmrmap.CMAP)
    assert cmap.shape == (256, 3)
    rows = [", ".join(repr(float(v)) for v in row) for row in cmap]
    lines = [
        "// Generated by tools/export_tables.py from Friture's CMRmap (Rappaport 2002).",
        "// Do not edit by hand.",
        "#pragma once",
        "",
        "namespace fr::tables {",
        "",
        "constexpr int kCmapSize = 256;",
        "constexpr float kCmap[kCmapSize][3] = {",
    ]
    lines += [f"    {{{r}}}," for r in rows]
    lines += ["};", "", "}  // namespace fr::tables"]
    (out / "generated_cmap.hpp").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    out = Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    export_filters(out)
    export_cmap(out)
    print("wrote", out)
